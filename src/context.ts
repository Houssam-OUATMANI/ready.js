/**
 * @file context.ts
 * @description Context object passed to middlewares and route handlers.
 * Encapsulates the incoming request (c.req) and JSON HTTP response builders (c.json).
 */

import { ReadyRequest } from "./request.js";

export class Context {
  /**
   * Strongly-typed wrapper around the incoming HTTP request.
   */
  public readonly req: ReadyRequest;

  /**
   * HTTP response headers configured for this context.
   */
  public readonly resHeaders: Headers = new Headers();

  /**
   * HTTP response status code (default: 200).
   */
  private _status: number = 200;

  /**
   * Key-value context state shared between middlewares (e.g. authenticated user).
   */
  private state: Map<string, unknown> = new Map();

  /**
   * Final response generated by c.json() or returned by a handler.
   */
  public finalResponse: Response | null = null;

  constructor(rawRequest: Request, params: Record<string, string> = {}) {
    this.req = new ReadyRequest(rawRequest, params);
  }

  /**
   * Fluently sets the HTTP response status code.
   *
   * @param code HTTP status code (e.g. 200, 201, 400, 404, 500)
   * @example
   * c.status(201);
   */
  public status(code: number): this {
    this._status = code;
    if (this.finalResponse && this.finalResponse.status !== code) {
      try {
        this.finalResponse = new Response(this.finalResponse.body, {
          status: code,
          statusText: this.finalResponse.statusText,
          headers: this.finalResponse.headers,
        });
      } catch {
        // Ignore if body is not reusable
      }
    }
    return this;
  }

  /**
   * Retrieves the currently configured HTTP status code.
   */
  public getStatusCode(): number {
    return this._status;
  }

  /**
   * Sets or appends an HTTP response header.
   * If a response has already been generated (e.g. after await next()),
   * it synchronizes the header directly on the active Response instance.
   *
   * @param name Header name (e.g. "X-Response-Time", "Authorization")
   * @param value Header value
   * @example
   * c.header("Cache-Control", "no-store");
   */
  public header(name: string, value: string): this {
    this.resHeaders.set(name, value);
    if (this.finalResponse) {
      try {
        this.finalResponse.headers.set(name, value);
      } catch {
        const headers = new Headers(this.finalResponse.headers);
        headers.set(name, value);
        this.finalResponse = new Response(this.finalResponse.body, {
          status: this.finalResponse.status,
          statusText: this.finalResponse.statusText,
          headers,
        });
      }
    }
    return this;
  }

  /**
   * Stores an arbitrary value in the request context for sharing across middlewares.
   *
   * @param key State key identifier
   * @param value Value to store
   * @example
   * c.set("user", { id: 1, role: "admin" });
   */
  public set(key: string, value: unknown): this {
    this.state.set(key, value);
    return this;
  }

  /**
   * Retrieves a stored value from the request context with generic typing.
   *
   * @template T Expected type of the stored value
   * @param key State key identifier
   * @example
   * const user = c.get<UserSession>("user");
   */
  public get<T = unknown>(key: string): T | undefined {
    return this.state.get(key) as T | undefined;
  }

  /**
   * Constructs and returns a standard Web Response formatted as JSON.
   * Automatically sets Content-Type to "application/json; charset=utf-8"
   * and attaches all custom headers defined via c.header().
   *
   * @param data Data payload to serialize as JSON
   * @param status Optional HTTP status code (overrides current status)
   * @returns Standard Web Response instance
   *
   * @example
   * return c.json({ success: true, count: 5 });
   * return c.json({ error: "Not Found" }, 404);
   */
  public json(data: unknown, status?: number): Response {
    if (status !== undefined) {
      this._status = status;
    }

    // Ensure standard JSON content type
    if (!this.resHeaders.has("Content-Type")) {
      this.resHeaders.set("Content-Type", "application/json; charset=utf-8");
    }

    const body = JSON.stringify(data);
    const response = new Response(body, {
      status: this._status,
      headers: this.resHeaders,
    });

    this.finalResponse = response;
    return response;
  }
}
